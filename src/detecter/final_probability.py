"""Fuse the base AI probability and sanitized metadata via TypeSafe Jev.

The Jev state contains only numbers, booleans and fixed enums: no image
bytes, no free text, no file identity. The Jev reasoning layer is asked to
explain a lone passive-model outlier (for example a UFD spike on an iPhone
photo with computational-photography processing) before the final
probability is combined with the passive maximum.
"""

from __future__ import annotations

import math
import time
from collections.abc import Mapping
from typing import Any

from .base_probability import calibrated_ai_probability

JEV_MODEL = "jev-1.13.0"
# Base weight of the Jev probability vs the passive-model maximum.
# Jev's confidence raises the weight toward 1.0, so a confident "lone
# outlier explained by computational photography" answer actually
# suppresses the passive spike instead of being averaged against it.
JEV_WEIGHT = 0.5

AI_INVOLVEMENT_CRITERIA = {
    "ai_generated": (
        "The evidence supports that the image was wholly or largely "
        "generated by an AI model."
    ),
    "ai_edited": (
        "A real photograph was partially edited, inpainted or composited "
        "with AI-generated content."
    ),
    "authentic_capture": (
        "The evidence supports an authentic camera capture. Smartphone "
        "computational photography (Smart HDR, Deep Fusion, night mode, "
        "AI denoise) and a lone passive-detector outlier score do not by "
        "themselves indicate AI generation."
    ),
    "inconclusive": (
        "The evidence is incomplete or contradictory and supports no "
        "conclusion either way."
    ),
}
CONFIDENCE_CRITERIA = [
    "Level 0: signals are missing or unusable; no reliable judgment.",
    "Level 1: weak or partial signals only; low reliability.",
    "Level 2: mixed signals with unresolved conflicts.",
    "Level 3: consistent signals across independent evidence.",
    "Level 4: decisive cryptographic or multi-model agreement.",
]
QUESTION_INSTRUCTIONS = (
    "Evaluate AI involvement in this image from the sanitized forensic "
    "state only. Treat passive detector scores as uncalibrated signals, "
    "not probabilities. When computational_photography_detected is true "
    "and exactly one passive model is an outlier against the others, "
    "prefer the phone's processing pipeline as the explanation and do "
    "not let that single score drive the probability."
)

CAMERA_DEVICE_CATEGORIES = {"smartphone", "camera", "scanner", "unknown"}
SYNTHID_STATES = {"detected", "not_detected", "not_checked", "unverifiable"}
_C2PA_STATES = {"present", "absent", "skipped", "error"}
_CONFIRMATION_STATES = {
    "trusted",
    "cryptographically_valid",
    "untrusted",
    "binding_unknown",
    "unverifiable",
    "hash_mismatch",
    "not_checked",
    "absent",
}


def _finite(value: Any, name: str) -> float | None:
    if value is None:
        return None
    score = float(value)
    if not math.isfinite(score):
        raise ValueError(f"{name} must be a finite number")
    return score


def _enum(value: Any, allowed: set[str], default: str) -> str:
    return value if isinstance(value, str) and value in allowed else default


def _clamp01(value: float) -> float:
    return min(1.0, max(0.0, value))


def _outlier_models(scores: Mapping[str, float]) -> list[str]:
    """Passive models whose normalized score deviates from the rest.

    A model is an outlier when it alone sits >= 0.5 on the AI side while
    every other available score sits below it, or the reverse.
    """
    outliers: list[str] = []
    for name, score in scores.items():
        others = [value for key, value in scores.items() if key != name]
        if others and all((score >= 0.5) != (other >= 0.5) for other in others):
            outliers.append(name)
    return outliers


def build_final_state(
    *,
    cf_score: float | None = None,
    cure_score: float | None = None,
    ufd_score: float | None = None,
    c2pa: Mapping[str, Any] | None = None,
    synthid: Mapping[str, Any] | None = None,
    media: Mapping[str, Any] | None = None,
    device_category: str = "unknown",
    computational_photography_detected: bool = False,
) -> dict[str, Any]:
    """Build the sanitized structured State for Jev.

    Only numbers, booleans and fixed enums are emitted. Free text fields
    (make, model strings, comments), hashes, paths and image data are
    never copied into the state.
    """
    cf = _finite(cf_score, "cf_score")
    cure = _finite(cure_score, "cure_score")
    ufd = _finite(ufd_score, "ufd_score")
    base = calibrated_ai_probability(cf, cure, ufd)

    c2pa = c2pa or {}
    synthid = synthid or {}
    media = media or {}
    # Normalize the passive scores into [0, 1] for a comparable outlier view.
    normalized = {
        name: value
        for name, value in (
            ("cf384", 1.0 / (1.0 + math.exp(-cf)) if cf is not None else None),
            ("cure", cure),
            ("ufd", ufd),
        )
        if value is not None
    }
    outliers = _outlier_models(normalized)

    image: dict[str, Any] = {}
    for key in ("width", "height"):
        value = media.get(key)
        if isinstance(value, int) and not isinstance(value, bool) and value > 0:
            image[key] = value
    if isinstance(media.get("format"), str) and media["format"].isalpha():
        image["format"] = media["format"]

    return {
        "base_ai_probability": round(base["probability"], 6),
        "base_partial": bool(base["partial"]),
        "passive_scores": {name: round(value, 6) for name, value in normalized.items()},
        "passive_outlier_models": outliers,
        "lone_outlier": len(outliers) == 1,
        "c2pa": {
            "status": _enum(c2pa.get("status"), _C2PA_STATES, "error"),
            "confirmation_state": _enum(
                c2pa.get("confirmation_state"), _CONFIRMATION_STATES, "unverifiable"
            ),
            "ai_claim": bool(
                c2pa.get("ai_source_assertion") or c2pa.get("ai_disclosure_assertion")
            ),
            "generation_scope": _enum(
                c2pa.get("generation_scope"), {"full", "partial", "unknown"}, "unknown"
            ),
        },
        "synthid_state": _enum(synthid.get("state"), SYNTHID_STATES, "not_checked"),
        "device_category": _enum(device_category, CAMERA_DEVICE_CATEGORIES, "unknown"),
        "computational_photography_detected": bool(computational_photography_detected),
        "image": image,
    }


def jev_questions() -> dict[str, Any]:
    """The parallel Jev question set: probability, conflict, confidence."""
    from typesafe_sdk import Choice, Noul, Score

    return {
        "ai_involvement": Choice(
            instructions=QUESTION_INSTRUCTIONS,
            criteria=dict(AI_INVOLVEMENT_CRITERIA),
        ),
        "evidence_conflict": Noul(
            instructions=(
                "Do the signals in the state materially conflict with each "
                "other (for example one passive detector spikes while "
                "provenance and the other models disagree)?"
            ),
            criteria={
                "true": "Signals disagree in a way that weakens the verdict.",
                "false": "Signals are consistent or independently weak.",
            },
        ),
        "confidence": Score(
            instructions=(
                "How reliable is the AI-involvement judgment given the "
                "completeness and agreement of the available evidence?"
            ),
            criteria=list(CONFIDENCE_CRITERIA),
        ),
    }


def _field(value: Any, name: str, default: Any = None) -> Any:
    if isinstance(value, dict):
        return value.get(name, default)
    return getattr(value, name, default)


def final_ai_probability(
    client: Any,
    *,
    cf_score: float | None = None,
    cure_score: float | None = None,
    ufd_score: float | None = None,
    c2pa: Mapping[str, Any] | None = None,
    synthid: Mapping[str, Any] | None = None,
    media: Mapping[str, Any] | None = None,
    device_category: str = "unknown",
    computational_photography_detected: bool = False,
) -> dict[str, Any]:
    """Query Jev once and combine its probability with the passive max.

    Returns ``final_ai_probability`` in [0.0, 1.0] and a confidence score.
    A Jev request failure is recorded as ``status: error`` instead of
    raising, so callers keep the sanitized state for diagnosis.
    """
    state = build_final_state(
        cf_score=cf_score,
        cure_score=cure_score,
        ufd_score=ufd_score,
        c2pa=c2pa,
        synthid=synthid,
        media=media,
        device_category=device_category,
        computational_photography_detected=computational_photography_detected,
    )
    started = time.perf_counter()
    try:
        response = client.system_one(state=state, questions=jev_questions())
    except Exception as error:  # noqa: BLE001
        return {
            "status": "error",
            "state": state,
            "requested_model": JEV_MODEL,
            "error_type": type(error).__name__,
            "duration_ms": round((time.perf_counter() - started) * 1000, 3),
        }

    answers = _field(response, "answers", {})
    involvement = (
        _field(answers.get("ai_involvement"), "root", None) or answers["ai_involvement"]
    )
    probabilities = dict(_field(involvement, "probabilities", {}))
    jev_probability = _clamp01(
        probabilities.get("ai_generated", 0.0) + probabilities.get("ai_edited", 0.0)
    )
    conflict = _clamp01(
        float(
            _field(
                _field(answers.get("evidence_conflict"), "root", None)
                or answers["evidence_conflict"],
                "noul",
                0.0,
            )
        )
    )
    confidence_answer = (
        _field(answers.get("confidence"), "root", None) or answers["confidence"]
    )
    level_max = len(CONFIDENCE_CRITERIA) - 1
    evidence_strength = _clamp01(
        float(_field(confidence_answer, "score", 0.0)) / level_max
    )
    answer_confidence = _clamp01(float(_field(confidence_answer, "confidence", 0.0)))
    confidence = _clamp01(answer_confidence * (1.0 - 0.5 * conflict))

    passive_max = max([state["base_ai_probability"], *state["passive_scores"].values()])
    blend = _clamp01(JEV_WEIGHT + JEV_WEIGHT * confidence)
    final = _clamp01(blend * jev_probability + (1.0 - blend) * passive_max)
    return {
        "status": "ok",
        "final_ai_probability": round(final, 6),
        "confidence": round(confidence, 6),
        "jev_probability": round(jev_probability, 6),
        "passive_max": round(passive_max, 6),
        "evidence_conflict": round(conflict, 6),
        "evidence_strength": round(evidence_strength, 6),
        "ai_involvement": _field(involvement, "choice"),
        "ai_involvement_probabilities": probabilities,
        "jev_weight": round(blend, 6),
        "requested_model": JEV_MODEL,
        "actual_model": _field(response, "model"),
        "usage": {
            "input_tokens": _field(_field(response, "usage"), "input_tokens"),
            "output_tokens": _field(_field(response, "usage"), "output_tokens"),
        },
        "state": state,
        "duration_ms": round((time.perf_counter() - started) * 1000, 3),
    }
